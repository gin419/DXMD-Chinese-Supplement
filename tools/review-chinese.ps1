$changed = 0
foreach ($list in $json.textlists) {
    foreach ($entry in @($list.content)) {
        $id = [string]$entry.id
        $before = [string]$entry.string
        if ($corrections.ContainsKey($id)) {
            $after = $corrections[$id]
        } else {
            $after = $before
            foreach ($key in $globalReplacements.Keys) {
                $after = $after.Replace($key, $globalReplacements[$key])
            }
            $after = $after.Replace('Augs', '增强人')
            $after = $after.Replace('普理查德', '普里查德').Replace('栅栏刀片', '栅栏的刀锋')
        }
        if ($after -ne $before) { $entry.string = $after; $changed++ }
    }
}

